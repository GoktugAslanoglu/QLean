#!/usr/bin/env python3
"""Print the C include of ASCII keywords from the pinned Lean Init environment."""
import argparse
from pathlib import Path
import re
import subprocess

PIN = "commit 611c117bfaf7b7ae1cfcf246ce6fba31e8f509e9,"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lean", default="lean")
    args = parser.parse_args()
    version = subprocess.check_output([args.lean, "--version"], text=True, timeout=5)
    if not version.startswith("Lean (version 4.36.0,") or PIN not in version:
        raise ValueError(f"expected official Lean 4.36.0, got {version.strip()}")
    probe = Path(__file__).with_name("lean_keywords.lean")
    output = subprocess.check_output([args.lean, "--run", str(probe)], text=True, timeout=30)
    words = {w for w in output.splitlines() if re.fullmatch(r"[A-Za-z][A-Za-z0-9_]*", w)}
    words.add("admit")
    if not {"theorem", "fun", "let", "sorry"} <= words or any(
        w.startswith("qlean_") for w in words
    ):
        raise ValueError("unexpected keyword table")
    print("/* Generated by scripts/update_keywords.py from Lean 4.36.0 Init. */")
    for word in sorted(words):
        print(f'    "{word}",')


if __name__ == "__main__":
    main()
